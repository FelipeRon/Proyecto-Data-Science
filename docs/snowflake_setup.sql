-- Administrator runs once. Replace public key BEFORE executing user creation.
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS PSET2_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS PSET2;
CREATE SCHEMA IF NOT EXISTS PSET2.RAW;
CREATE SCHEMA IF NOT EXISTS PSET2.BRONZE;
CREATE SCHEMA IF NOT EXISTS PSET2.SILVER;
CREATE SCHEMA IF NOT EXISTS PSET2.GOLD;
CREATE SCHEMA IF NOT EXISTS PSET2.OBT;
CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT USAGE ON DATABASE PSET2 TO ROLE PSET2_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT ON ALL SCHEMAS IN DATABASE PSET2 TO ROLE PSET2_ROLE;
